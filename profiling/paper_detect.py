class PropagationKernel:
    """Step C reduced to the part that changes between bootstrap replicates.

    The call-graph multiplicities and the top-level weights are graph properties: they do not
    depend on which iterations a replicate happened to draw. Precomputing them once turns a
    replicate into a handful of multiply-adds, which is what makes 1000 replicates tractable
    (a full `propagate()` per replicate would re-run a DFS per (top-level, deviated) pair).
    """

    def __init__(self, traces: dict, deviated_sigs, summary: dict, weight: str = "none",
                 production=None, top_level_scope=None, base_means_full: dict = None,
                 aggregation: str = "construct"):
        if aggregation not in ("construct", "outermost"):
            raise ValueError(f"unknown aggregation mode: {aggregation!r}")
        self.aggregation = aggregation
        graph = build_graph(traces, summary, production=production,
                            top_level_scope=top_level_scope)
        self.weight_mode = weight
        self.top_level = [s for s in graph["top_level"] if s in summary]
        self.excluded = graph["excluded"]
        # Test-harness components have no system-level counterpart, so they cannot propagate.
        deviated_sigs = [d for d in deviated_sigs if d in graph["nodes"]]
        self.weights = {
            r: (float(graph["root_calls"].get(r, 0)) if weight == "calls" else 1.0)
            for r in self.top_level
        }
        # {top_level: {deviated: multiplicity}}, zero-multiplicity pairs dropped.
        self.mult: dict[str, dict[str, float]] = {}
        for r in self.top_level:
            row = {}
            for d in deviated_sigs:
                m = multiplicity(graph, summary, r, d)
                if m > 0.0:
                    row[d] = m
            self.mult[r] = row
        self.deviated_sigs = list(deviated_sigs)
        # Full-data mean per top-level signature, used when a replicate does not contain one.
        # Defaults to the summary's own means so the kernel is safe to build without it.
        self.base_means_full = dict(base_means_full or
                                    {s: r["mean_ns"] for s, r in summary.items()})

    def totals(self, base_means: dict[str, float],
               cand_means: dict[str, float]) -> tuple[float, float]:
        """(baseline subsystem total, updated subsystem total) in ns, weighted.

        A top-level signature missing from `base_means` falls back to its FULL-DATA mean rather
        than being skipped. Skipping it — the behaviour until 2026-08-15 — removed it from the
        denominator as well as the numerator, so the subsystem total silently shrank and the
        relative deviation inflated with no error raised. Demonstrated on lift: dropping the
        single largest non-feature top-level component moved the denominator 11.69 -> 8.96 ms
        and relDev +132.8% -> +173.3%; dropping three gave +213%.

        This was latent while every signature appeared in every replicate, but it blocks the
        setup-phase exclusion: excluding setup records legitimately removes signatures from the
        resampled means, and with the old behaviour that produced a bootstrap CI which did not
        bracket its own point estimate — proof the bootstrap statistic had drifted from the
        full-data anchor it is normalised against.
        """
        md = {}
        for d in self.deviated_sigs:
            b, c = base_means.get(d), cand_means.get(d)
            if b is None or c is None:
                continue
            md[d] = c - b
        base_total = upd_total = 0.0
        for r in self.top_level:
            w = self.weights[r]
            if w == 0.0:
                continue
            b_r = base_means.get(r)
            if b_r is None:
                b_r = self.base_means_full.get(r)
            if b_r is None:
                continue
            if self.aggregation == "outermost" and r in self.deviated_sigs and r in md:
                prop = md[r]
            else:
                prop = sum(md[d] * m for d, m in self.mult[r].items() if d in md)
            base_total += b_r * w
            upd_total += (b_r + prop) * w
        return base_total, upd_total

    def totals_variants(self, base_means: dict[str, float],
                        cand_means: dict[str, float]) -> dict:
        """Subsystem totals under the three readings of §III-C's aggregation.

        Called ONCE on the full data, never inside a bootstrap replicate — `totals()` stays the
        hot path. Reported so the port's modelling choice is visible in the row rather than
        implicit in the number.

        `construct` is the shipped reading: every deviated node's MD propagated up by call
        multiplicity and summed. The paper does not define it. §III-C's entire edge spec is
        "edges representing their interaction dependencies (e.g., function calls). Performance
        information is represented as node attributes" — nothing on edges — and its only mention
        of call counts rejects them as a "naive approach". So this is THIS PORT'S resolution of
        a case §III-C leaves open: what to do when a top-level and one of its own callees both
        deviate (Fig. 3 marks only leaf nodes B3/B4, never a caller+callee pair). Kieker
        OperationExecutionRecord times are INCLUSIVE, so in that case the callee's MD is counted
        twice — once inside the caller's own measured MD, once as its own contribution.

        `measured` is §III-C read literally: "we calculate the overall performance of the
        subsystem by summing up the top-level component performance", justified by top-levels
        "encompass[ing] the performance of their invoked components". With inclusive data that
        is the directly measured top-level delta, and it cannot double-count. Matches
        paper_propagate.propagate()'s `crosscheck_measured_relative_deviation`.

        `outermost` keeps the propagation where it still earns its place. A top-level that step
        B did not flag has no trustworthy measured delta of its own, so its deviated descendants
        are summed as in `construct`; one that IS flagged uses its own MD, which already contains
        them. This is the reading the paper's stated rationale supports, and it is the only one
        of the three that both avoids the double-count and recovers a diluted signal.

        `nested_excess_ns` is the double-counted quantity itself: the weighted contribution of
        deviated callees of deviated top-levels. Deterministic, not noise — it is exactly
        `construct - outermost`.
        """
        deviated = set(self.deviated_sigs)
        md = {}
        for d in self.deviated_sigs:
            b, c = base_means.get(d), cand_means.get(d)
            if b is None or c is None:
                continue
            md[d] = c - b
        base_total = upd_construct = upd_measured = upd_outermost = 0.0
        n_nested = 0
        nested_excess_ns = 0.0
        nested_top_level = []
        for r in self.top_level:
            w = self.weights[r]
            if w == 0.0:
                continue
            b_r = base_means.get(r)
            if b_r is None:
                b_r = self.base_means_full.get(r)
            if b_r is None:
                continue
            prop = sum(md[d] * m for d, m in self.mult[r].items() if d in md)
            # Direct inclusive measurement of the same top-level, independent of the graph.
            c_r, b_r_meas = cand_means.get(r), base_means.get(r)
            meas = (c_r - b_r_meas) if (c_r is not None and b_r_meas is not None) else 0.0
            if r in deviated and r in md:
                outer = md[r]
                nested = sum(md[d] * m for d, m in self.mult[r].items()
                             if d in md and d != r)
                if nested:
                    n_nested += 1
                    nested_excess_ns += nested * w
                    nested_top_level.append(r)
            else:
                outer = prop
            base_total += b_r * w
            upd_construct += (b_r + prop) * w
            upd_measured += (b_r + meas) * w
            upd_outermost += (b_r + outer) * w

        def _rel(upd):
            return (upd - base_total) / base_total if base_total > 0 else 0.0

        return {
            "baseline_subsystem_ns": base_total,
            "updated_subsystem_ns": upd_construct,
            "relative_deviation": _rel(upd_construct),
            "measured_relative_deviation": _rel(upd_measured),
            "outermost_relative_deviation": _rel(upd_outermost),
            "nested_excess_ns": nested_excess_ns,
            "n_nested_deviated_top_level": n_nested,
            "nested_deviated_top_level": sorted(nested_top_level),
        }


def _bootstrap_limitation(n_base: int, n_cand: int):
    """Describe the block bootstrap's actual resolution, from the blocks that actually ran.

    The paper's protocol gives 30 in-session repeats, which `parse_run_tagged` rebuckets into 30
    blocks. A profile carrying far fewer blocks (this project's superseded 5-invocation runs)
    resamples coarsely and understates tail uncertainty; one carrying 30 does not. Reporting a
    fixed string made every honest 30-repeat profile disclose a limitation it did not have.
    """
    n = min(n_base, n_cand)
    if n >= 30:
        return None
    return (f"{n} bootstrap blocks, fewer than the paper's 30 — block resampling is coarse "
            f"and understates tail uncertainty")


def _ci_straddles_no_change(lo, hi) -> bool | None:
    """True when the demand-scale CI contains 1.0, i.e. the profile does not pin down direction.

    Note this is NOT the effect-size threshold: the verdict's delta=0.147 gate applies to Cliff's
    Delta over predicted response times, a different quantity on a different axis. What is
    checkable here is whether the measurements are consistent with no demand change at all. When
    they are, the point-estimate verdict flips under resampling, and that should be machine
    readable rather than left for a reader to infer from the percentiles.
    """
    if lo is None or hi is None:
        return None
    return lo <= 1.0 <= hi


def _means_from_iterations(stats: dict[str, dict[str, dict]], iters) -> dict[str, float]:
    """Per-signature mean over a (possibly repeated) selection of iteration labels."""
    out = {}
    for sig, per_it in stats.items():
        s = n = 0.0
        for it in iters:
            rec = per_it.get(it)
            if rec:
                s += rec["sum"]
                n += rec["n"]
        if n > 0:
            out[sig] = s / n
    return out


def _means_iid(raw: dict[str, list], rng: random.Random) -> dict[str, float]:
    """Per-signature mean of an iid bootstrap resample within each signature."""
    out = {}
    for sig, xs in raw.items():
        n = len(xs)
        if not n:
            continue
        out[sig] = sum(xs[rng.randrange(n)] for _ in range(n)) / n
    return out


def detect_from_data(base_raw: dict, cand_raw: dict, traces: dict, summary: dict,
                     model: dict, weight: str = "none",
                     normalize: str = "none", bootstrap: str = "block",
                     n_replicates: int = 1000, control_sigs=None,
                     seed: int = 20260727, scaled_station: str = None,
                     base_tagged: dict = None, cand_tagged: dict = None,
                     n_samples: int = 20000, top_level_scope=None,
                     scope_label: str = "unit-test-roots",
                     class_aware: bool = False,
                     aggregation: str = "construct",
                     visits: dict = None,
                     target_class: str = None,
                     class_scale: bool = False) -> dict:
    """Steps B -> C -> D on already-loaded measurements.

    Split out from `detect()` so the same code path serves both this project's profile
    directories AND the paper's own replication data, whose local measurements are bare
    `kieker.dat` files rather than our profile layout. Validating against the paper's numbers
    with a DIFFERENT implementation than the one used on the thesis dataset would validate
    nothing, so there is exactly one implementation here.

    base_raw/cand_raw: {sig: [exec_ns]}
    traces:            {"edges": [...], "entry_points": [...]} of the BASELINE
    summary:           {sig: {n_calls, mean_ns}} of the BASELINE
    base_tagged/cand_tagged: {sig: {iteration: {"sum","n"}}}, required for bootstrap="block"
    scaled_station:    which model station step C's deviation applies to
                       (default: model["scaled_station"])
    """
    rng = random.Random(seed)

    # --- Step B on the complete data. The DEVIATED SET is fixed here, once. Re-running the
    # significance test inside every replicate would be both prohibitively slow and
    # conceptually wrong: the bootstrap is propagating uncertainty in the MD estimates through
    # the model, not re-deciding which components the paper's rule selects.
    stepb = identify_deviations(base_raw, cand_raw, control_sigs=control_sigs,
                               normalize=normalize)
    k = stepb["run_offset"]["ratio"] if stepb["run_offset"]["applied"] else 1.0
    deviated_sigs = [c["operation_signature"] for c in stepb["deviated"]]

    # Full-data reference totals: the normalisation anchor, so that a replicate which happens
    # to reproduce the full senior profile maps exactly onto the model's own service demand.
    base_means_full = {s: r["mean_ns"] for s, r in summary.items()}

    kernel = PropagationKernel(traces, deviated_sigs, summary, weight=weight,
                               top_level_scope=top_level_scope,
                               base_means_full=base_means_full,
                               aggregation=aggregation)
    cand_means_full = {s: (sum(v) / len(v)) / k for s, v in cand_raw.items() if v}
    base_total_full, upd_total_full = kernel.totals(base_means_full, cand_means_full)
    rel_dev_full = ((upd_total_full - base_total_full) / base_total_full
                    if base_total_full > 0 else 0.0)
    variants = kernel.totals_variants(base_means_full, cand_means_full)

    # Built here rather than in the return so the SATURATED path below reports them too. Until
    # 2026-08-21 a saturated network returned early with no step_b/step_c at all, which left the
    # five saturated features' aggregation unauditable from the shipped rows.
    stepb_block = {"normalize": normalize, "run_offset": stepb["run_offset"],
                   "n_compared": stepb["n_compared"],
                   "n_deviated": len(stepb["deviated"]),
                   "deviated": [{"operation_signature": c["operation_signature"],
                                 "md_ms": c["md_ms"], "p_value": c["p_value"],
                                 "cliffs_delta": c["cliffs_delta"],
                                 "magnitude": c["magnitude"]} for c in stepb["deviated"]],
                   "new_components": stepb["new_components"],
                   "removed_components": stepb["removed_components"]}
    stepc_block = {
        "weight": weight, "aggregation": aggregation, "top_level_scope": scope_label,
        "n_top_level": len(kernel.top_level),
        "baseline_subsystem_ms": base_total_full / 1e6,
        "updated_subsystem_ms": upd_total_full / 1e6,
        # The three readings of §III-C's aggregation — see PropagationKernel.totals_variants.
        # `relative_deviation` above is the `construct` one; these two are the alternatives it
        # is being compared against, recorded per row so the comparison needs no re-run.
        "crosscheck_measured_relative_deviation": variants["measured_relative_deviation"],
        "crosscheck_discrepancy": rel_dev_full - variants["measured_relative_deviation"],
        "literal_outermost_relative_deviation": variants["outermost_relative_deviation"],
        "nested_excess_ms": variants["nested_excess_ns"] / 1e6,
        "n_nested_deviated_top_level": variants["n_nested_deviated_top_level"],
        "nested_deviated_top_level": variants["nested_deviated_top_level"],
    }

    station = scaled_station or model["scaled_station"]
    demands = dict(model["demands"])
    if station not in demands:
        raise ValueError(f"scaled_station {station!r} not among model demands {list(demands)}")

    # --- Bootstrap
    if bootstrap == "block":
        if base_tagged is None or cand_tagged is None:
            raise ValueError("bootstrap='block' needs base_tagged/cand_tagged "
                             "(per-iteration stats)")
        b_stats, c_stats = base_tagged, cand_tagged
        b_iters = sorted({it for per in b_stats.values() for it in per})
        c_iters = sorted({it for per in c_stats.values() for it in per})
        if not b_iters or not c_iters:
            raise ValueError("no iteration labels found — samples_tagged.csv missing/empty")
    elif bootstrap == "iid":
        b_stats = c_stats = None
        b_iters = c_iters = []
    else:
        raise ValueError(f"unknown bootstrap mode: {bootstrap!r}")

    # --- Bootstrap: a confidence interval on the propagated deviation. This quantifies how
    # well the 5-iteration profile pins down the demand scaling. It is REPORTED, not used as
    # the verdict — see below.
    scales = []
    for _ in range(n_replicates):
        if bootstrap == "block":
            bm = _means_from_iterations(
                b_stats, [b_iters[rng.randrange(len(b_iters))] for _ in b_iters])
            cm = _means_from_iterations(
                c_stats, [c_iters[rng.randrange(len(c_iters))] for _ in c_iters])
        else:
            bm = _means_iid(base_raw, rng)
            cm = _means_iid(cand_raw, rng)
        if k != 1.0:
            cm = {s: v / k for s, v in cm.items()}
        bt, ut = kernel.totals(bm, cm)
        if bt > 0:
            scales.append(ut / bt)
    scales.sort()

    def _pct(xs, q):
        return xs[min(len(xs) - 1, max(0, int(q * len(xs))))] if xs else None

    # --- Step D proper. Solve the ORIGINAL and UPDATED models and compare their predicted
    # response-time DISTRIBUTIONS with the paper's test.
    #
    # The distributions are per-request response times drawn from the M/M/m network
    # (qn_solver.sample_response_times), which is what SimQPN produces for the paper. Using the
    # bootstrap spread above instead would be wrong: it measures uncertainty in our demand
    # ESTIMATE, which is far narrower than the response-time variability the effect size is
    # meant to be judged against, and it drives Cliff's Delta to 1.0 for arbitrarily small
    # shifts. Validating against the paper's own data is what exposed that.
    demands_orig = dict(demands)
    demands_upd = dict(demands)
    per_class_orig = model.get("per_class_service_s")
    per_class_upd = None
    if per_class_orig:
        per_class_upd = {st: dict(cls_map) for st, cls_map in per_class_orig.items()}

    delta_s = (upd_total_full - base_total_full) / 1e9

    if target_class is not None and class_scale:
        mix = model.get("request_mix") or {}
        p_c = mix.get(target_class, 1.0)
        if per_class_upd and station in per_class_upd and target_class in per_class_upd[station]:
            base_s = per_class_orig[station][target_class]
            add_s = delta_s if delta_s > 0 else (base_s * rel_dev_full)
            per_class_upd[station][target_class] = base_s + add_s
            demands_upd[station] = demands_orig[station] + p_c * add_s
        else:
            demands_upd[station] = demands[station] * (1.0 + rel_dev_full)
    else:
        demands_upd[station] = demands[station] * (1.0 + rel_dev_full)

    solved_o = solve(model, demands_orig)
    solved_u = solve(model, demands_upd)
    sat_stations = sorted(set(solved_o["saturated"]) | set(solved_u["saturated"]))

    # Explicit pre-solve saturation feasibility check:
    # If offered load meets or exceeds capacity (rho >= 1.0), the queue explodes to infinity.
    # We bypass stochastic sampling and emit a deterministic saturation bypass verdict.
    if solved_u["saturated"]:
        sampler_desc = f"endpoint-scoped ({target_class})" if target_class else ("class-aware" if class_aware else "mix-averaged")
        return {
            "predicted_regression": True,
            "verdict_type": "saturation_bypass",
            "saturated": True,
            "saturated_stations": sat_stations,
            "saturation_detail": f"Station(s) {sat_stations} exceed capacity (rho >= 1.0)",
            "scaled_station": station,
            "target_class": target_class,
            "endpoint_scoped": target_class is not None,
            "relative_deviation": rel_dev_full,
            "demand_scale": 1.0 + rel_dev_full,
            "aggregation": aggregation,
            "rule": "saturation_bypass: demand scaling drives station utilization rho >= 1.0 (infinite queue / bottleneck collapse)",
            "p_value": 0.0,
            "cliffs_delta": 1.0,
            "effect_magnitude": "large",
            "mpd_response_time_ms": float("inf"),
            "mpd_cpu_percent": 100.0 - (solved_o["utilization"].get(station, 0.0) * 100.0) if station in solved_o["utilization"] else 0.0,
            "predicted_response_time_ms": {
                "original": solved_o["response_time_s"] * 1000.0 if not math.isinf(solved_o["response_time_s"]) else float("inf"),
                "updated": float("inf")
            },
            "predicted_cpu_percent": {
                "original": solved_o["utilization"].get(station, 0.0) * 100.0 if station in solved_o["utilization"] else 0.0,
                "updated": 100.0
            },
            "service_demand_s": {"original": demands[station],
                                 "updated": demands_upd[station]},
            "scaled_station": station,
            "response_time_samples": 0,
            "sampler": sampler_desc,
            "demand_scale_ci": {"mode": bootstrap, "replicates": len(scales),
                                "p2.5": _pct(scales, 0.025), "p50": _pct(scales, 0.50),
                                "p97.5": _pct(scales, 0.975),
                                "n_blocks_baseline": len(b_iters),
                                "n_blocks_candidate": len(c_iters),
                                "limitation": _bootstrap_limitation(len(b_iters), len(c_iters)),
                                "ci_straddles_no_change": _ci_straddles_no_change(
                                    _pct(scales, 0.025), _pct(scales, 0.975))},
            "note": "network saturated at this demand scaling; classified as regression via saturation bypass rule",
            "step_b": stepb_block,
            "step_c": stepc_block,
            "model": {"form": model.get("form"), "provenance": model.get("provenance"),
                      "arrival_rate": model.get("arrival_rate"),
                      "servers": model.get("servers"),
                      "n_users": model.get("n_users"), "demands": demands},
        }

    sampler_desc = f"endpoint-scoped ({target_class})" if target_class else ("class-aware" if class_aware else "mix-averaged")
    try:
        r_orig = sample_response_times(model, demands_orig, n_samples, rng,
                                       class_aware=class_aware or (target_class is not None),
                                       visits=visits,
                                       target_class=target_class,
                                       per_class_service=per_class_orig)
        r_upd = sample_response_times(model, demands_upd, n_samples, rng,
                                      class_aware=class_aware or (target_class is not None),
                                      visits=visits,
                                      target_class=target_class,
                                      per_class_service=per_class_upd)
    except SaturatedError as exc:
        return {
            "predicted_regression": True,
            "verdict_type": "saturation_bypass",
            "saturated": True,
            "saturated_stations": sat_stations,
            "saturation_detail": str(exc),
            "scaled_station": station,
            "target_class": target_class,
            "endpoint_scoped": target_class is not None,
            "relative_deviation": rel_dev_full,
            "demand_scale": 1.0 + rel_dev_full,
            "aggregation": aggregation,
            "rule": "saturation_bypass: demand scaling drives station utilization rho >= 1.0 (infinite queue / bottleneck collapse)",
            "p_value": 0.0,
            "cliffs_delta": 1.0,
            "effect_magnitude": "large",
            "mpd_response_time_ms": float("inf"),
            "mpd_cpu_percent": 100.0 - (solved_o["utilization"].get(station, 0.0) * 100.0) if station in solved_o["utilization"] else 0.0,
            "predicted_response_time_ms": {
                "original": solved_o["response_time_s"] * 1000.0 if not math.isinf(solved_o["response_time_s"]) else float("inf"),
                "updated": float("inf")
            },
            "predicted_cpu_percent": {
                "original": solved_o["utilization"].get(station, 0.0) * 100.0 if station in solved_o["utilization"] else 0.0,
                "updated": 100.0
            },
            "service_demand_s": {"original": demands[station],
                                 "updated": demands_upd[station]},
            "scaled_station": station,
            "response_time_samples": 0,
            "sampler": sampler_desc,
            "demand_scale_ci": {"mode": bootstrap, "replicates": len(scales),
                                "p2.5": _pct(scales, 0.025), "p50": _pct(scales, 0.50),
                                "p97.5": _pct(scales, 0.975),
                                "n_blocks_baseline": len(b_iters),
                                "n_blocks_candidate": len(c_iters),
                                "limitation": _bootstrap_limitation(len(b_iters), len(c_iters)),
                                "ci_straddles_no_change": _ci_straddles_no_change(
                                    _pct(scales, 0.025), _pct(scales, 0.975))},
            "note": "network saturated at this demand scaling; classified as regression via saturation bypass rule",
            "step_b": stepb_block,
            "step_c": stepc_block,
            "model": {"form": model.get("form"), "provenance": model.get("provenance"),
                      "arrival_rate": model.get("arrival_rate"),
                      "servers": model.get("servers"),
                      "n_users": model.get("n_users"), "demands": demands},
        }

    p_value = wilcoxon_rank_sum(r_orig, r_upd)
    delta, magnitude = cliffs_delta(r_orig, r_upd)

    # MPD from the analytic solve — exact, and free of sampling noise.
    if target_class is not None:
        cls_o = class_response_time(model, demands_orig, target_class, per_class_service=per_class_orig)
        cls_u = class_response_time(model, demands_upd, target_class, per_class_service=per_class_upd)
        mean_o = cls_o["response_time_s"]
        mean_u = cls_u["response_time_s"]
    else:
        mean_o = solved_o["response_time_s"]
        mean_u = solved_u["response_time_s"]

    cpu_o = solved_o["utilization"][station] * 100.0
    cpu_u = solved_u["utilization"][station] * 100.0

    # Directionality guards: p <= 0.05 AND magnitude != "negligible" AND delta > 0 AND mean_u > mean_o
    # Eliminates false regression alarms on performance speedups.
    predicted = (p_value <= P_THRESHOLD and
                 magnitude != "negligible" and
                 delta > 0 and
                 mean_u > mean_o)

    return {
        "predicted_regression": predicted,
        "verdict_type": "analytically_solved",
        "aggregation": aggregation,
        "rule": "wilcoxon p <= 0.05 AND cliffs delta non-negligible (Liao et al. III-D) "
                "AND delta > 0 AND mean_updated > mean_original (directionality guard)",
        "p_value": p_value,
        "cliffs_delta": delta,
        "effect_magnitude": magnitude,
        "mpd_response_time_ms": (mean_u - mean_o) * 1000.0,
        "mpd_cpu_percent": cpu_u - cpu_o,
        "predicted_response_time_ms": {"original": mean_o * 1000.0, "updated": mean_u * 1000.0},
        "predicted_cpu_percent": {"original": cpu_o, "updated": cpu_u},
        "relative_deviation": rel_dev_full,
        "demand_scale": 1.0 + rel_dev_full,
        "service_demand_s": {"original": demands[station],
                             "updated": demands_upd[station]},
        "scaled_station": station,
        "target_class": target_class,
        "endpoint_scoped": target_class is not None,
        "response_time_samples": n_samples,
        "sampler": sampler_desc,
        "saturated": False,
        "saturated_stations": sat_stations,
        # The bootstrap now reports how tightly the profile pins down the demand scaling; it
        # does not decide the verdict.
        "demand_scale_ci": {"mode": bootstrap, "replicates": len(scales),
                            "p2.5": _pct(scales, 0.025), "p50": _pct(scales, 0.50),
                            "p97.5": _pct(scales, 0.975),
                            "n_blocks_baseline": len(b_iters),
                            "n_blocks_candidate": len(c_iters),
                            # Was hardcoded to "5 iterations, not the paper's 30" — false for
                            # every in-session 30-repeat profile, i.e. for every profile the
                            # re-measurement produces. Derive it from what actually ran.
                            "limitation": _bootstrap_limitation(len(b_iters), len(c_iters)),
                            # The verdict conditions on the point estimate alone (paper-literal).
                            # When the CI spans the effect-size threshold the verdict is a coin
                            # flip on resampling; say so in a field rather than in prose.
                            "ci_straddles_no_change": _ci_straddles_no_change(
                                _pct(scales, 0.025), _pct(scales, 0.975))},
        "step_b": stepb_block,
        "step_c": stepc_block,
        "model": {"form": model.get("form"), "provenance": model.get("provenance"),
                  "arrival_rate": model.get("arrival_rate"),
                  # Per-station server count decides BOTH step-D boundaries (utilisation is
                  # lambda*D/m), so a row that omits it cannot be audited: the same demand scale
                  # is a regression under one server count and saturated under another.
                  "servers": model.get("servers"),
                  "n_users": model.get("n_users"), "demands": demands},
    }


def detect(baseline_profile: str, candidate_profile: str, model: dict,
           weight: str = "none", normalize: str = "none",
           bootstrap: str = "block", n_replicates: int = 1000,
           control_sigs=None, seed: int = 20260727,
           scaled_station: str = None, top_level_scope=AUTO_SCOPE,
           class_aware: bool = False,
           aggregation: str = "construct",
           n_samples: int = 20000,
           visits: dict = None,
           target_class: str = None,
           class_scale: bool = False) -> dict:
    """Run steps B -> C -> D for one senior/junior profile-directory pair.

    Thin loader over `detect_from_data`: reads samples.csv / samples_tagged.csv / traces.json /
    summary.csv out of the two profile dirs and delegates.

    `top_level_scope` defaults to AUTO_SCOPE: derive the «REST API» subsystem boundary from the
    workspace the baseline profile sits in (see paper_propagate's TOP-LEVEL SCOPE note). That
    is the paper's rule, so it is what you get unless you ask otherwise. Pass None to opt out
    and fall back to "every production component the unit test called directly", or a predicate
    to supply your own. Whichever applies is recorded in `step_c.top_level_scope`, because a
    denominator that changes silently is not reproducible.
    """
    scope_label = "unit-test-roots"
    if top_level_scope is AUTO_SCOPE:
        ws = workspace_for_profile(baseline_profile)
        if ws is None:
            top_level_scope = None
        else:
            pairs = rest_exposed_operations(ws)
            top_level_scope = make_rest_scope(pairs)
            scope_label = f"rest:{os.path.basename(ws)}({len(pairs)} exposed)"
    elif top_level_scope is not None:
        scope_label = "rest:explicit"
    base_raw = load_samples(os.path.join(baseline_profile, "samples.csv"))
    cand_raw = load_samples(os.path.join(candidate_profile, "samples.csv"))

    with open(os.path.join(baseline_profile, "traces.json")) as fh:
        traces = json.load(fh)
    summary = load_summary(os.path.join(baseline_profile, "summary.csv"))

    base_tagged = cand_tagged = None
    if bootstrap == "block":
        base_tagged = per_iteration_stats(load_samples_tagged(
            os.path.join(baseline_profile, "samples_tagged.csv")))
        cand_tagged = per_iteration_stats(load_samples_tagged(
            os.path.join(candidate_profile, "samples_tagged.csv")))

    return detect_from_data(base_raw, cand_raw, traces, summary, model,
                            weight=weight, normalize=normalize, bootstrap=bootstrap,
                            n_replicates=n_replicates, control_sigs=control_sigs,
                            seed=seed, scaled_station=scaled_station,
                            base_tagged=base_tagged, cand_tagged=cand_tagged,
                            n_samples=n_samples,
                            top_level_scope=top_level_scope, scope_label=scope_label,
                            class_aware=class_aware,
                            aggregation=aggregation,
                            visits=visits,
                            target_class=target_class,
                            class_scale=class_scale)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("baseline_profile")
    ap.add_argument("candidate_profile")
    ap.add_argument("--model", required=True, help="architectural model descriptor JSON")
    ap.add_argument("--weight", choices=["none", "calls"], default="none")
    ap.add_argument("--aggregation", choices=["construct", "outermost"], default="construct",
                    help="Step C aggregation rule: 'construct' (sum all reachable) or 'outermost' (prune callees of deviated roots)")
    ap.add_argument("--samples", type=int, default=20000,
                    help="number of response-time samples to draw per model in Step D (default: 20000)")
    ap.add_argument("--target-class", default=None,
                    help="target request class / URL endpoint for endpoint-scoped detection (e.g. loginaction, category, product)")
    ap.add_argument("--class-scale", action="store_true",
                    help="scale service demand specifically on the target class rather than aggregate station demand")
    ap.add_argument("--normalize", choices=["none", "control-median"], default="none")
    ap.add_argument("--bootstrap", choices=["block", "iid"], default="block")
    ap.add_argument("--replicates", type=int, default=1000)
    ap.add_argument("--seed", type=int, default=20260727,
                    help="RNG seed for step D's bootstrap resampling. Provenance-only: "
                         "recording and exposing the value already used by default, not "
                         "changing detect()'s behaviour. Two verdicts (stockoutrisk TP, "
                         "substitutes FP) sit inside the seed-fragile detection band "
                         "(x1.728-x1.861) — re-running with a different --seed is how that "
                         "fragility gets demonstrated instead of asserted .")
    ap.add_argument("--controls-from", default=None)
    ap.add_argument("--rest-scope", default=None, metavar="WORKSPACE",
                    help="override the workspace whose REST endpoints define step C's "
                         "top-level components. Defaults to the baseline profile's own "
                         "workspace, which is almost always what you want.")
    ap.add_argument("--no-rest-scope", action="store_true",
                    help="opt out of the «REST API» subsystem boundary and fall back to "
                         "'every production component the unit test called directly'. Not the "
                         "paper's rule; kept for comparison with pre-2026-08-06 results.")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    with open(args.model) as fh:
        model = json.load(fh)

    controls = None
    cfrom = args.controls_from or os.path.join(
        os.path.dirname(os.path.abspath(args.candidate_profile)), "compare.csv")
    if args.normalize == "control-median" and os.path.isfile(cfrom):
        controls = load_control_sigs(cfrom)

    if args.no_rest_scope and args.rest_scope:
        ap.error("--no-rest-scope and --rest-scope are mutually exclusive")
    if args.no_rest_scope:
        scope = None
    elif args.rest_scope:
        scope = make_rest_scope(rest_exposed_operations(args.rest_scope))
    else:
        scope = AUTO_SCOPE

    rep = detect(args.baseline_profile, args.candidate_profile, model,
                 weight=args.weight, normalize=args.normalize, bootstrap=args.bootstrap,
                 n_replicates=args.replicates, control_sigs=controls,
                 seed=args.seed, top_level_scope=scope,
                 aggregation=args.aggregation, n_samples=args.samples,
                 target_class=args.target_class, class_scale=args.class_scale)
    # Report what step C actually summed over. When AUTO finds no workspace it falls back
    # silently by design (the paper's own replication data has no source tree), so this line
    # is the only place that difference is visible.
    scope_label = rep["step_c"]["top_level_scope"]
    if scope_label != "unit-test-roots":
        print(f"  top-level scope: {scope_label}")
    elif args.no_rest_scope:
        print("  top-level scope: unit-test roots — opted out of the «REST API» boundary, "
              "so this is NOT the paper's rule")
    else:
        # AUTO asked for the boundary and could not find one. Distinct from opting out, and
        # the more dangerous case: nobody chose it, so it has to be loud.
        print("  top-level scope: unit-test roots — NO persistence REST layer beside "
              f"{args.baseline_profile!r}, so the paper's boundary could not be applied")

    verdict = "REGRESSION" if rep["predicted_regression"] else "no regression"
    if rep.get("verdict_type") == "saturation_bypass":
        verdict = "REGRESSION (saturation bypass)"
    print(f"predicted: {verdict}")
    if rep.get("verdict_type") == "saturation_bypass":
        print(f"  rule: {rep['rule']}")
        print(f"  saturated stations: {rep['saturated_stations']}")
        print(f"  relative deviation: {rep['relative_deviation']:+.4%}")
    else:
        print(f"  p={rep['p_value']:.4g}  cliffs_delta={rep['cliffs_delta']:+.4f} "
              f"({rep['effect_magnitude']})")
        print(f"  MPD response time: {rep['mpd_response_time_ms']:+.4f} ms   "
              f"MPD CPU: {rep['mpd_cpu_percent']:+.4f} pp")
        print(f"  predicted RT: {rep['predicted_response_time_ms']['original']:.4f} -> "
              f"{rep['predicted_response_time_ms']['updated']:.4f} ms")
    print(f"  local deviation -> demand scale x{rep['demand_scale']:.5f} "
          f"on station '{rep['scaled_station']}' "
          f"({rep['step_b']['n_deviated']}/{rep['step_b']['n_compared']} components deviated)")
    ci = rep["demand_scale_ci"]
    print(f"  demand-scale 95% CI ({ci['mode']} bootstrap, {ci['replicates']} reps): "
          f"[{ci['p2.5']:.5f}, {ci['p97.5']:.5f}]")
    print(f"  predicted RT sampled from {rep['response_time_samples']} draws per model"
          + (f"   !! SATURATED: {rep['saturated_stations']}"
             if rep["saturated_stations"] else ""))

    if args.out:
        with open(args.out, "w") as fh:
            json.dump(rep, fh, indent=1)
        print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
