#!/usr/bin/env python3
"""
paper_detect.py — STEP D of Liao et al., ICSE'25: detecting system performance regressions
from the original vs updated architectural model (§III-D).

    "We first use both models to get the original and updated predicted performance, including
     the resource utilization and response time. We then utilize a statistical analysis
     approach similar to the one used for identifying local performance deviation in Section
     III-B. In particular, we utilize the Wilcoxon rank-sum test and Cliff's Delta effect size
     ... If the p-value is smaller than 0.05 and the effect size is larger than negligible, we
     would consider that the changes to the software may lead to system performance
     regressions."

WHERE THE DISTRIBUTIONS COME FROM. The paper's statistical test needs two SAMPLES of predicted
performance. It gets them from simulation: SimQPN is stochastic and it repeats each run three
times. Our solver (qn_solver.py) is analytic, so one solve is a single number and there is
nothing for a rank test to rank. The variance that actually matters here is not simulator
noise anyway — it is measurement uncertainty in the service demand we estimated from the
Kieker profile. So the distributions are generated by BOOTSTRAPPING the measurements through
steps B/C/D:

  * BLOCK bootstrap over iterations (default). The iteration is the independent replicate:
    calls within one iteration share JIT state, GC timing and cache warmth, so resampling
    individual calls would treat correlated observations as independent and produce
    confidence intervals that are far too tight. Iterations are resampled with replacement.
  * `--bootstrap iid` resamples per-call within each signature instead, as a sensitivity run.

  RESOLVED 2026-07-30 (previously: "this dataset has 5 iterations, not the paper's 30").
  Checked directly against the paper's own replication package: their 30 iterations are 30
  repetitions INSIDE one Kieker session, not 30 separate test invocations. This project's
  profiling harnesses (kieker_profile.sh, dual_track.py) now match that — one in-session
  profile per track, with FeaturePerfExerciseTest repeating each catalog-wide query 30 times
  inside it — and parse_kieker.py's `parse_run_tagged` rank-rebuckets that single session
  into 30 `rep_NN` blocks by execution order, the same structure block=1 (this project's
  earlier 5 separate `mvn test` invocations) understated. Validated against the paper's own
  `Component_perf_res/L2_Original/kieker.dat`: the same rank-based logic recovers exactly 30
  blocks of 5 calls each for its 150-call operations.

BOTH SIDES VARY. A naive implementation would hold the original model fixed (its demand comes
from the architectural model, not from our measurements) and vary only the updated one, which
would make the rank test trivially significant. Instead each replicate resamples the senior
and junior profiles independently and derives BOTH demands from those resamples, normalised so
that the full-data senior profile reproduces the model's own demand exactly. The test then
asks whether predicted response time differs by more than measurement uncertainty explains.

MPD (mean performance degradation) is reported for response time in ms and for CPU percentage
from station utilization, matching the two column groups of the paper's Table I.
"""
